/**
 * Checks whether a given state or cloud snapshot is just the generic Nigerian sample demo dataset
 */
export function isSampleSeedData(stateOrData: any): boolean {
  if (!stateOrData) return false;
  if (stateOrData.businessName === 'Chidi & Sons Ventures') return true;
  if (Array.isArray(stateOrData.events) && stateOrData.events.length > 0) {
    const hasSampleId = stateOrData.events.some((e: any) =>
      typeof e?.id === 'string' && (e.id.startsWith('ev-today-') || e.id.startsWith('ev-yesterday-') || e.id.includes('seed'))
    );
    const hasSampleProduct = stateOrData.products?.some((p: any) =>
      p?.id === 'prod-rice' && p?.name === 'Rice'
    );
    if (hasSampleId && hasSampleProduct) return true;
  }
  return false;
}
